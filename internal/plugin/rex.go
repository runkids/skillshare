const rexHeader = "-- Generated by Skillshare; format 1; do not edit.\n"
const rexLine = `pcall(dofile, ((os.getenv("XDG_STATE_HOME") ~= "" and os.getenv("XDG_STATE_HOME")) or (package.config:sub(1,1) == "\\" and os.getenv("AppData") ~= "" and os.getenv("AppData")) or ((package.config:sub(1,1) == "\\" and os.getenv("USERPROFILE") or os.getenv("HOME")) .. "/.local/state")) .. "/skillshare/skillshare_rex.lua") -- skillshare:rex` + "\n"

// rexID follows rexd/internal/manifest/manifest.go idPattern.
var rexID = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*(\.[a-z0-9][a-z0-9-]*)+$`)

type rexManifest struct {
	ID, Version, Config, Main string
}
type rexEntry struct {
	rexManifest
	Dir string
}

func rexInitPath() string {
	if p := os.Getenv("REX_CONFIG"); p != "" {
		return p
	}
	base := os.Getenv("XDG_CONFIG_HOME")
	if runtime.GOOS == "windows" {
		base = os.Getenv("AppData")
	}
	if base == "" {
		home, _ := os.UserHomeDir()
		base = filepath.Join(home, ".config")
	}
	return filepath.Join(base, "rex", "init.lua")
}

func rexManifestProblem(root string, m map[string]json.RawMessage, info *TargetPackage) {
	var id, config string
	_ = json.Unmarshal(m["id"], &id)
	_ = json.Unmarshal(m["config"], &config)
	if len(id) > 64 || !rexID.MatchString(id) {
		info.block("plugins.problem.manifestName", "rex-plugin.toml requires a valid plugin name", map[string]string{"manifest": "rex-plugin.toml"})
		return
	}
	if string(m["scripts"]) != "" && string(m["scripts"]) != "[]" || string(m["build"]) != "" && string(m["build"]) != "[]" {
		info.block("plugins.problem.rexScripts", "Event scripts and build steps need rexd's daemon; Skillshare installs config code only.", nil)
		return
	}
	if config == "" {
		info.block("plugins.problem.rexNoConfig", "Rex plugins require a config file.", nil)
		return
	}
	realRoot, rootErr := filepath.EvalSymlinks(root)
	resolved, resolveErr := filepath.EvalSymlinks(filepath.Join(root, filepath.FromSlash(config)))
	rel, relErr := filepath.Rel(realRoot, resolved)
	if rootErr != nil || resolveErr != nil || relErr != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || !isRegularFile(resolved) {
		info.block("plugins.problem.rexConfigEscapes", "Rex config must be an existing file inside the plugin.", nil)
	}
}

func (s *Service) rexHost(ctx context.Context, target string) Host {
	h := Host{Target: target, Status: HostReady, Installed: []Installed{}, NoteKey: "plugins.note.rex", Note: "Config code only; run rex config reload after changes."}
	var err error
	h.Installed, h.Fingerprint, err = s.localInventory("rex")
	if err != nil {
		h.fail(err)
		return h
	}
	data, err := s.run(ctx, target, "version", "--json")
	if errors.Is(err, ErrCLIMissing) {
		h.Status = HostMissing
		h.NoteKey = "plugins.note.rexMissing"
		h.Note = "Rex is not installed here; this will be applied on a machine that has it."
		return h
	}
	if err != nil {
		h.fail(err)
		return h
	}
	var version struct {
		Version string `json:"rex_version"`
	}
	if err = json.Unmarshal(data, &version); err != nil {
		h.fail(err)
		return h
	}
	h.Version = version.Version
	return h
}

// rexAdopt follows rexd's Amber module and source naming rules.
func rexAdopt(dir, location, commit string) (rexManifest, error) {
	repo, owner := "", "local"
	if filepath.IsAbs(location) {
		repo = strings.TrimSuffix(filepath.Base(filepath.Clean(location)), ".git")
	} else {
		parts := strings.FieldsFunc(strings.TrimSuffix(strings.TrimRight(location, "/"), ".git"), func(r rune) bool { return r == '/' || r == ':' })
		if len(parts) == 0 {
			return rexManifest{}, fmt.Errorf("missing Rex source name")
		}
		repo = parts[len(parts)-1]
		if len(parts) > 1 {
			owner = parts[len(parts)-2]
		}
	}
	name := strings.TrimSuffix(repo, ".rex")
	var modules []string
	for _, sub := range []string{"rex/lua", "lua"} {
		entries, err := os.ReadDir(filepath.Join(dir, filepath.FromSlash(sub)))
		if err != nil {
			continue
		}
		for _, e := range entries {
			if e.IsDir() && isRegularFile(filepath.Join(dir, filepath.FromSlash(sub), e.Name(), "init.lua")) {
				modules = append(modules, e.Name())
			} else if !e.IsDir() && filepath.Ext(e.Name()) == ".lua" {
				modules = append(modules, strings.TrimSuffix(e.Name(), ".lua"))
			}
		}
		break
	}
	if len(modules) == 0 {
		return rexManifest{}, fmt.Errorf("no Rex manifest or Lua module found")
	}
	main := modules[0]
	if len(modules) > 1 {
		main = ""
		for _, m := range modules {
			if m == name {
				main = m
				break
			}
		}
		if main == "" {
			return rexManifest{}, fmt.Errorf("several Lua modules and none named %s; add rex-plugin.toml", name)
		}
	}
	clean := regexp.MustCompile(`[^a-z0-9-]+`)
	part := func(s string) string { return strings.Trim(clean.ReplaceAllString(strings.ToLower(s), "-"), "-") }
	id := part(owner) + "." + part(name)
	if len(id) > 64 || !rexID.MatchString(id) {
		return rexManifest{}, fmt.Errorf("invalid adopted Rex plugin id %q", id)
	}
	version := "local"
	if commit != "" {
		version = commit[:min(len(commit), 7)]
	}
	return rexManifest{ID: id, Version: version, Main: main}, nil
}

func rexReadEntry(dir, source, commit string) (rexEntry, error) {
	if _, err := os.Stat(filepath.Join(dir, "rex-plugin.toml")); os.IsNotExist(err) {
		m, e := rexAdopt(dir, source, commit)
		return rexEntry{rexManifest: m, Dir: dir}, e
	}
	c, err := inspect(dir)
	if err != nil {
		return rexEntry{}, err
	}
	info, ok := c.TargetInfo["rex"]
	if !ok {
		return rexEntry{}, fmt.Errorf("no Rex manifest found")
	}
	if info.Problem != "" {
		return rexEntry{}, errors.New(info.Problem)
	}
	return rexEntry{rexManifest: rexManifest{ID: c.Name, Version: info.Version, Config: info.rexConfig}, Dir: dir}, nil
}

// rexLuaQuote preserves arbitrary path bytes in Lua's decimal escape syntax.
func rexLuaQuote(value string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(value); i++ {
		c := value[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c < 32 || c >= 127:
			fmt.Fprintf(&b, `\%03d`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func (s *Service) rexEntries(root string) ([]rexEntry, error) {
	installed, err := os.ReadDir(root)
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	var entries []rexEntry
	for _, item := range installed {
		if !item.IsDir() || strings.HasPrefix(item.Name(), ".") {
			continue
		}
		var metadata cursorOwner
		marker, _ := os.ReadFile(filepath.Join(root, ".skillshare-"+item.Name()+".json"))
		_ = json.Unmarshal(marker, &metadata)
		e, err := rexReadEntry(filepath.Join(root, item.Name()), metadata.RexSource, metadata.RexCommit)
		if err != nil {
			return nil, fmt.Errorf("Rex plugin %s: %w", filepath.Join(root, item.Name()), err)
		}
		entries = append(entries, e)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].ID < entries[j].ID })
	return entries, nil
}

// rexExpectedLoader validates loader ownership and returns the loader text.
func (s *Service) rexExpectedLoader(entries []rexEntry, data []byte) (string, error) {
	owner := rexHeader + "-- skillshare-root: " + hash([]byte(s.managedRoot())) + "\n"
	if data != nil && !strings.HasPrefix(string(data), owner) {
		return "", fmt.Errorf("Rex loader is unrecognized or belongs to another Skillshare configuration or version; delete this loader file before retrying")
	}
	return strings.Replace(rexLoader(entries, false), rexHeader, owner, 1), nil
}

func rexLoader(entries []rexEntry, probe bool) string {
	var b strings.Builder
	b.WriteString(rexHeader)
	b.WriteString("rexd = rexd or { plugins = {} }\nrexd.plugins = rexd.plugins or {}\n")
	for _, e := range entries {
		lua := filepath.Join(e.Dir, "rex", "lua")
		if !isDirectory(lua) {
			lua = filepath.Join(e.Dir, "lua")
		}
		onError := `rex.log("error", tostring(err))`
		if probe {
			onError = `error(` + rexLuaQuote("Rex plugin "+e.ID+": ") + ` .. tostring(err))`
		}
		call := "dofile, " + rexLuaQuote(filepath.ToSlash(filepath.Join(e.Dir, e.Config)))
		if e.Main != "" {
			call = "function() require(" + rexLuaQuote(e.Main) + ").setup(rexd.plugin.options) end"
		}
		fmt.Fprintf(&b, "do\n  local dir = %s\n  package.path = %s .. package.path\n  local previous = rexd.plugin\n  local plugin = { id = %s, version = %s, dir = dir, options = {} }\n  rexd.plugin = plugin\n  rexd.plugins[plugin.id] = plugin\n  local ok, err = pcall(%s)\n  rexd.plugin = previous\n  if not ok then %s end\nend\n", rexLuaQuote(filepath.ToSlash(e.Dir)), rexLuaQuote(filepath.ToSlash(lua)+"/?.lua;"+filepath.ToSlash(lua)+"/?/init.lua;"), rexLuaQuote(e.ID), rexLuaQuote(e.Version), call, onError)
	}
	return b.String()
}

func rexLineIndex(content string) int {
	for offset := 0; offset < len(content); {
		start := offset
		if start == 0 && strings.HasPrefix(content, "\xef\xbb\xbf") {
			start = 3
		}
		if rexManagedLine(content[start:]) {
			return start
		}
		next := strings.IndexByte(content[offset:], '\n')
		if next < 0 {
			break
		}
		offset += next + 1
	}
	return -1
}

func rexManagedLine(content string) bool {
	line, _, _ := strings.Cut(content, "\n")
	return strings.TrimSuffix(line, "\r") == strings.TrimSuffix(rexLine, "\n")
}

// rexWriteInit saves init.lua, or deletes it when Skillshare created it and nothing is left.
func rexWriteInit(init, dest, content string, deleteFile bool) error {
	if deleteFile {
		if info, e := os.Lstat(init); e == nil && info.Mode()&os.ModeSymlink == 0 {
			return os.Remove(dest)
		}
	}
	mode := os.FileMode(0644)
	if info, e := os.Stat(dest); e == nil {
		mode = info.Mode().Perm()
	}
	return atomicNativeWrite(filepath.Dir(dest), dest, []byte(content), mode)
}

func (s *Service) applyRex(ctx context.Context, c Change, binding Binding, source string) error {
	init := rexInitPath()
	loader := filepath.Join(s.StateDir, "skillshare_rex.lua")
	dest, err := utils.ConfigWritePath(init, false)
	if err != nil {
		return err
	}
	data, err := os.ReadFile(loader)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	if _, err = s.rexExpectedLoader(nil, data); err != nil {
		return fmt.Errorf("%s: %w", loader, err)
	}
	root, _, err := s.localRoot("rex")
	if err != nil {
		return err
	}

	// Like rexd's Layout.Check, probe the incoming plugin alone.
	if c.Action == "install" || c.Action == "update" {
		entry, err := rexReadEntry(source, binding.Source, binding.Commit)
		if err != nil {
			return err
		}
		dir, err := os.MkdirTemp("", "skillshare-rex-check-")
		if err != nil {
			return err
		}
		defer os.RemoveAll(dir)
		probe := filepath.Join(dir, "probe.lua")
		if err = os.WriteFile(probe, []byte(rexLoader([]rexEntry{entry}, true)), 0600); err != nil {
			return err
		}
		if _, err = s.run(ctx, c.Target, "config", "check", probe, "--json"); err != nil {
			return err
		}
	}

	if err := s.applyLocal(c, binding, source); err != nil {
		return err
	}
	return s.reconcileRex(init, dest, loader, root)
}

func (s *Service) reconcileRex(init, dest, loader, root string) error {
	original, err := os.ReadFile(dest)
	initExisted := err == nil
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	data, err := os.ReadFile(loader)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	rec, found, err := rexInitState(root, data != nil, string(original), initExisted)
	if err != nil {
		return err
	}
	entries, err := s.rexEntries(root)
	if err != nil {
		return err
	}
	content, next := string(original), rec
	if len(entries) == 0 {
		if len(data) > 0 {
			if err = os.Remove(loader); err != nil {
				return err
			}
		}
		if rec.InsertedLine {
			content = rexRemoveLine(content)
		}
	} else {
		expected, err := s.rexExpectedLoader(entries, data)
		if err != nil {
			return err
		}
		if string(data) != expected {
			if err = atomicNativeWrite(filepath.Dir(loader), loader, []byte(expected), 0644); err != nil {
				return err
			}
		}
		if rexLineIndex(content) < 0 {
			if content, err = rexInsertLine(content); err != nil {
				return err
			}
			next.InsertedLine = true
		}
		if !found || next != rec {
			if err = rexWriteRecord(root, next); err != nil {
				return err
			}
		}
	}
	if content != string(original) {
		if err = rexWriteInit(init, dest, content, content == "" && rec.CreatedInit); err != nil {
			return err
		}
	}
	if len(entries) == 0 {
		return rexRemoveRecord(root)
	}
	return nil
}

// rexNeedsRepair compares managed wiring with the locally installed bundles.
func (s *Service) rexNeedsRepair() (bool, error) {
	root, _, err := s.localRoot("rex")
	if err != nil {
		return false, err
	}
	entries, err := s.rexEntries(root)
	if err != nil || len(entries) == 0 {
		return false, err
	}
	loader := filepath.Join(s.StateDir, "skillshare_rex.lua")
	data, err := os.ReadFile(loader)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	expected, err := s.rexExpectedLoader(entries, data)
	if err != nil {
		return false, fmt.Errorf("%s: %w", loader, err)
	}
	init, err := os.ReadFile(rexInitPath())
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	return string(data) != expected || rexLineIndex(string(init)) < 0, nil
}

func (s *Service) rexSyncRepair(r Request, c Change) error {
	if r.Action != "sync" || c.Target != "rex" || !c.Binding.Selected() {
		return nil
	}
	needs, err := s.rexNeedsRepair()
	if err != nil || !needs {
		return err
	}
	init := rexInitPath()
	dest, err := utils.ConfigWritePath(init, false)
	if err != nil {
		return err
	}
	root, _, err := s.localRoot("rex")
	if err != nil {
		return err
	}
	return s.reconcileRex(init, dest, filepath.Join(s.StateDir, "skillshare_rex.lua"), root)
}
